(async () => {
  const platform = App.createUserscriptPlatform();
  const store = App.createSettingsStore(platform);
  await store.init();
  GM_addStyle(App.readerCss);
  App.createReader(platform, store);
  let panel = null;
  const openSettings = () => {
    if (panel) return;
    const host = document.createElement('div');
    host.setAttribute('data-at-ui', '');
    const root = host.attachShadow({ mode: 'open' });
    const style = document.createElement('style');
    style.textContent = App.settingsCss;
    root.append(style);
    const overlay = document.createElement('div');
    overlay.className = 'at-dialog';
    const box = document.createElement('div');
    box.className = 'at-dialog-panel';
    box.setAttribute('role', 'dialog');
    box.setAttribute('aria-label', 'AnonTranslator 设置');
    const button = document.createElement('button');
    button.className = 'at-close';
    button.textContent = '关闭 ×';
    const unmount = App.mountSettings(box, store, platform);
    const close = () => { unmount(); host.remove(); panel = null; document.removeEventListener('keydown', onEscape); };
    const onEscape = event => { if (event.code === 'Escape') close(); };
    button.addEventListener('click', close);
    overlay.addEventListener('click', event => { if (event.target === overlay) close(); });
    document.addEventListener('keydown', onEscape);
    box.prepend(button); overlay.append(box); root.append(overlay);
    document.documentElement.append(host);
    panel = host;
    button.focus();
  };
  GM_registerMenuCommand('AnonTranslator 设置', openSettings);
})().catch(error => console.error('AnonTranslator:', error));
