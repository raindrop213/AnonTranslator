import vm from 'node:vm';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const read = file => readFile(new URL(`../${file}`, import.meta.url), 'utf8');
const defaults = JSON.parse(await read('src/config/defaultSettings.json'));
const context = vm.createContext({ fetch, AbortSignal, URL, URLSearchParams, Uint8Array, btoa, atob, setTimeout, clearTimeout });
vm.runInContext(`const App = ${JSON.stringify({ defaults })}`, context);
for (const file of ['shortcuts', 'settings', 'services']) vm.runInContext(await read(`src/core/${file}.js`), context);
const app = vm.runInContext('App', context);
const speakers = await app.handleServiceMessage({ action: 'vits_speakers', settings: defaults });
const selected = speakers.voices.find(voice => voice.id === defaults.vitsVoice) || speakers.voices[0];
console.log(JSON.stringify({ voices: speakers.voices.length, selected }));
const audio = await app.handleServiceMessage({ action: 'vits_audio', text: 'こんにちは。これは音声のテストです。', settings: { ...defaults, vitsVoice: selected.id } });
const bytes = Buffer.from(audio.audio, 'base64');
await mkdir(new URL('../test-results/', import.meta.url), { recursive: true });
await writeFile(new URL('../test-results/vits-test.mp3', import.meta.url), bytes);
console.log(JSON.stringify({ mime: audio.mime, bytes: bytes.length, output: 'test-results/vits-test.mp3' }));
