import { readFile, writeFile, mkdir, cp, rm } from 'node:fs/promises';
import path from 'node:path';
import { root, version, extensionPath, userscriptPath, chromeDir, userscriptDir, projectURL, release } from './paths.mjs';

const read = file => readFile(path.join(root, file), 'utf8');
const defaults = JSON.parse(await read('src/config/defaultSettings.json'));
const readerCss = await read('src/ui/reader.css');
const settingsCss = await read('src/ui/settings.css');
const headerImages = Object.fromEntries(await Promise.all([['on', 'img2.jpg'], ['off', 'img3.jpg']].map(async ([state, file]) => [state, 'data:image/jpeg;base64,' + (await readFile(path.join(root, 'docs/images', file))).toString('base64')])));
const banner = `// Generated by scripts/build.mjs. Edit src/, then rebuild.\n`;
// Explicit composition keeps the toolchain dependency-free. Every source file
// runs inside one strict closure and exposes its public functions through App.
async function bundle(files, resources = {}) {
  const app = JSON.stringify({ defaults, version, release, ...resources });
  // version.js also exports pure helpers for Node; the closure needs no export keywords.
  const sources = await Promise.all(['core/version', 'core/shortcuts', ...files].map(async file => (await read(`src/${file}.js`)).replace(/^export /gm, '')));
  return `${banner}(() => {\n'use strict';\nconst App = ${app};\n${sources.join('\n\n')}\n})();\n`;
}
const distDir = path.join(root, 'dist');
await mkdir(distDir, { recursive: true });
// Only replace the two build targets; leave unrelated files untouched.
for (const output of [chromeDir, userscriptDir]) {
  if (path.dirname(output) !== distDir) throw new Error('Refusing to clean outside dist');
  await rm(output, { recursive: true, force: true });
}
await mkdir(chromeDir, { recursive: true });
await mkdir(userscriptDir, { recursive: true });
const manifest = JSON.parse(await read('src/platform/manifest.json'));
manifest.version = version;
await writeFile(path.join(chromeDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
await cp(path.join(root, 'assets/img'), path.join(chromeDir, 'assets/img'), { recursive: true });
await writeFile(path.join(chromeDir, 'content.js'), await bundle(['core/settings', 'core/services', 'core/text', 'core/audio', 'core/scroll', 'core/reader', 'platform/chromePermissions', 'platform/chrome', 'entries/content']));
await writeFile(path.join(chromeDir, 'background.js'), await bundle(['core/settings', 'core/updates', 'core/services', 'platform/chromePermissions', 'entries/background']));
await writeFile(path.join(chromeDir, 'popup.js'), await bundle(['core/settings', 'platform/chromePermissions', 'platform/chrome', 'ui/settings', 'entries/popup'], { headerImages }));
await writeFile(path.join(chromeDir, 'reader.css'), readerCss);
await writeFile(path.join(chromeDir, 'settings.css'), settingsCss);
await cp(path.join(root, 'LICENSE'), path.join(chromeDir, 'LICENSE'));
await writeFile(path.join(chromeDir, 'popup.html'), '<!doctype html>\n<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>AnonTranslator 设置</title><link rel="stylesheet" href="settings.css"></head><body><script src="popup.js"></script></body></html>\n');
const metadata = `// ==UserScript==
// @name         AnonTranslator
// @namespace    ${projectURL}
// @version      ${version}
// @homepageURL  ${projectURL}
// @supportURL   ${projectURL}/issues
// @description  复制、朗读与翻译网页段落；菜单中打开即时设置
// @author       raindrop213
// @license      MIT
// @match        http://*/*
// @match        https://*/*
// @match        file:///*
// @run-at       document-idle
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_addValueChangeListener
// @grant        GM_xmlhttpRequest
// @grant        GM_setClipboard
// @grant        GM_addStyle
// @grant        GM_registerMenuCommand
// @connect      127.0.0.1
// @connect      *
// @connect      translate-pa.googleapis.com
// @connect      translate.volcengine.com
// @connect      m.youdao.com
// @connect      api.github.com
// ==/UserScript==
`;
await writeFile(path.join(userscriptDir, 'AnonTranslator.user.js'), metadata + await bundle(['core/settings', 'core/updates', 'core/services', 'core/text', 'core/audio', 'core/scroll', 'core/reader', 'platform/userscript', 'ui/settings', 'entries/userscript'], { headerImages, readerCss, settingsCss }));
console.log(`Built ${extensionPath} and ${userscriptPath}`);
